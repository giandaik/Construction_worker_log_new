#!/usr/bin/env python3
"""Build the PDF font modules from the upstream Fira Sans TTFs.

The work-log sheet is set in Fira Sans (the design system's text face) because it
carries Greek and Latin in the same weight — a project name like «Σπίτι Γιάννη»
must not fall back to a system font mid-line. jsPDF needs a TTF it can embed, so
this script downloads the upstream faces, subsets them to the ranges the sheet can
print, and writes the base64 modules the renderer imports.

    uv run --with fonttools python3 scripts/build-pdf-fonts.py

Sources: github.com/google/fonts · ofl/firasans · SIL Open Font License 1.1.
Re-run only when the type face or the glyph set changes; the generated modules are
committed, exactly like the Roboto module they replace.
"""
from __future__ import annotations

import base64
import pathlib
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "app" / "fonts"
BASE = "https://raw.githubusercontent.com/google/fonts/main/ofl/firasans"

# 400 body · 600 emphasised values · 700 display (WORK LOG, project name)
FACES = {400: "FiraSans-Regular.ttf", 600: "FiraSans-SemiBold.ttf", 700: "FiraSans-Bold.ttf"}

# Latin (basic + supplement), Greek and Coptic, general punctuation, currency,
# degree/middle-dot/superscripts, arrows. Everything the sheet can print.
UNICODES = [
    (0x0020, 0x007E), (0x00A0, 0x00FF), (0x0131, 0x0131), (0x0152, 0x0153),
    (0x02B9, 0x02BF), (0x02C6, 0x02DA), (0x0300, 0x0301),
    (0x0370, 0x0377), (0x037A, 0x037F), (0x0384, 0x038A), (0x038C, 0x038C),
    (0x038E, 0x03A1), (0x03A3, 0x03FF),
    (0x2000, 0x206F), (0x20AC, 0x20AC), (0x2116, 0x2116), (0x2122, 0x2122),
    (0x2190, 0x2193), (0x2212, 0x2212), (0x2264, 0x2265),
]


def fetch(name: str) -> bytes:
    with urllib.request.urlopen(f"{BASE}/{name}", timeout=60) as res:
        return res.read()


def build(weight: int, filename: str) -> tuple[int, list[str]]:
    src = ROOT / ".pdf-font-cache" / filename
    src.parent.mkdir(exist_ok=True)
    if not src.exists():
        src.write_bytes(fetch(filename))

    font = TTFont(src)
    cmap = font.getBestCmap()
    missing = [hex(cp) for cp in (0x03A3, 0x03C0, 0x00B0, 0x00B7, 0x20AC, 0x2014) if cp not in cmap]
    if missing:
        raise SystemExit(f"{filename}: upstream font lacks {missing} — refusing to build a sheet it cannot print")

    opts = subset.Options()
    opts.layout_features = ["kern", "liga", "onum", "tnum", "pnum"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    # jsPDF never hints: dropping instructions and glyph names is ~35% smaller
    opts.hinting = False
    opts.glyph_names = False
    opts.recalc_bounds = True
    subsetter = subset.Subsetter(options=opts)
    subsetter.populate(unicodes=[cp for lo, hi in UNICODES for cp in range(lo, hi + 1)])
    subsetter.subset(font)

    tmp = ROOT / ".pdf-font-cache" / f"subset-{weight}.ttf"
    font.save(tmp)
    data = tmp.read_bytes()
    b64 = base64.b64encode(data).decode("ascii")

    out = OUT / f"fira-sans-{weight}.js"
    out.write_text(
        f"// Fira Sans {weight} · subset latin+greek · SIL OFL 1.1 · generated by scripts/build-pdf-fonts.py\n"
        f"const firaSans{weight} = \"{b64}\";\n\nexport default firaSans{weight};\n"
    )
    glyphs = len(font.getGlyphOrder())
    return len(b64), [str(glyphs)]


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for weight, filename in FACES.items():
        size, meta = build(weight, filename)
        print(f"app/fonts/fira-sans-{weight}.js  base64={size/1024:.1f} KiB  glyphs={meta[0]}")
